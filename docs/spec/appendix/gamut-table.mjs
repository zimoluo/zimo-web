import {cMax,oklchToHex} from "./oklch.mjs";
const hs=[]; for(let h=0;h<360;h+=15) hs.push(h);
console.log("# Appendix — sRGB gamut ceiling `Cmax(L, h)`\n");
console.log("Generated by `appendix/oklch.mjs`. Maximum OKLCh chroma representable in sRGB at each");
console.log("lightness and hue, found by bisection to 1e-5. This is the table that makes ADR-001");
console.log("necessary: a constant absolute chroma is unreachable for some hues and unremarkable for");
console.log("others, so chroma must be authored relative to this ceiling.\n");
console.log("## Ceiling by lightness and hue\n");
console.log("| L | "+hs.map(h=>`${h}°`).join(" | ")+" |");
console.log("| --- |"+hs.map(()=>" --- |").join(""));
for(let L=0.10;L<=0.99;L+=0.05){
  console.log(`| ${L.toFixed(2)} | `+hs.map(h=>cMax(L,h).toFixed(4)).join(" | ")+" |");
}
console.log("\n## Peak ceiling per hue, and where it occurs\n");
console.log("| hue | peak Cmax | at L |");
console.log("| --- | --- | --- |");
for(const h of hs){
  let best=0,bl=0;
  for(let L=0.02;L<=0.995;L+=0.0025){const c=cMax(L,h);if(c>best){best=c;bl=L;}}
  console.log(`| ${h}° | ${best.toFixed(4)} | ${bl.toFixed(3)} |`);
}
console.log("\n## Spread at fixed lightness\n");
console.log("The ratio between the most and least chromatic hue at a given lightness. This is the");
console.log("magnitude of the error an HSL-saturation ramp makes.\n");
console.log("| L | min Cmax | max Cmax | ratio |");
console.log("| --- | --- | --- | --- |");
for(const L of [0.20,0.30,0.40,0.50,0.60,0.70,0.80,0.85,0.90,0.95]){
  const vals=hs.map(h=>cMax(L,h));
  const mn=Math.min(...vals), mx=Math.max(...vals);
  console.log(`| ${L.toFixed(2)} | ${mn.toFixed(4)} | ${mx.toFixed(4)} | ${(mx/mn).toFixed(1)}× |`);
}
