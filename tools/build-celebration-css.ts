import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve as resolvePath } from "node:path";

const ROOT = resolvePath(import.meta.dirname, "..");
const OUT_PATH = join(
  ROOT,
  "src/features/backdrop/scenes/celebration/celebration.module.css",
);

const COUNT = 36;
const RING_SEGMENTS = 30;
const RING_RADIUS = 30;
const UNIT = 0.085;
const SEED = 0x5eed_1234;

let state = SEED;
const nextRandom = (): number => {
  state = (state * 1_664_525 + 1_013_904_223) % 4_294_967_296;
  return state / 4_294_967_296;
};

const randomInt = (max: number): number => Math.floor(nextRandom() * max) + 1;

const noScientific = (value: number): number =>
  Math.abs(value) < 0.000001 ? 0 : Math.round(value * 1_000_000) / 1_000_000;

const shadowValue = (
  radius: number,
  cosV: number,
  sinV: number,
  bokeh: number,
  color: string,
): string => {
  const parts: string[] = [];
  const push = (r: number): void => {
    parts.push(
      `${noScientific(r * cosV * UNIT)}vmax ${noScientific(r * sinV * UNIT)}vmax ` +
        `${noScientific(bokeh * UNIT)}vmax ${color}`,
    );
  };

  let current = radius;
  push(current);
  push(current - 1);

  current = current / 1.8;
  push(current);
  push(current - 1);

  current = current / 2;
  push(current);

  current = current / 10;
  push(current);

  return parts.join(" ,");
};

const ringEffect = (segments: number, radius: number, bokeh: number, color: string): string => {
  const parts = ["0px 0px var(--zw-scene-highlight)"];
  for (let i = 0; i <= segments; i += 1) {
    const radian = ((360 / segments) * i * 3.1416) / 180;
    parts.push(shadowValue(radius, Math.cos(radian), Math.sin(radian), bokeh, color));
  }
  return parts.join(" , ");
};

const blocks: string[] = [
  "/* Generated by tools/build-celebration-css.ts. Do not edit; run the tool.",
  "   Replaces celebration.module.scss, whose math.random() calls made the compiled",
  "   output differ on every build. The generator is seeded, so it is deterministic. */",
  "",
];

for (let i = 0; i <= COUNT; i += 1) {
  const top = `${randomInt(100)}%`;
  const left = `${randomInt(100)}%`;
  const hueOffset = randomInt(240);
  const color = `oklch(from var(--zw-scene-accent) l c calc(h + ${hueOffset}))`;

  blocks.push(`.fire${i} {
  top: ${top};
  left: ${left};
  color: ${color};
}

.fire${i} .ring1 {
  width: ${UNIT}vmax;
  height: ${UNIT}vmax;
  box-shadow: ${ringEffect(RING_SEGMENTS, RING_RADIUS, 0, "currentColor")};
}

.fire${i} .ring2 {
  width: ${UNIT}vmax;
  height: ${UNIT}vmax;
  box-shadow: ${ringEffect(RING_SEGMENTS, RING_RADIUS, 2, "currentColor")};
}`);
}

blocks.push(`.fireworks {
  opacity: 0;
  position: absolute;
}`);

for (let i = 0; i <= COUNT; i += 1) {
  const duration = randomInt(8) + 2;
  const scale = randomInt(7);

  blocks.push(`.pattern${i} {
  animation-name: pattern${i};
  animation-duration: calc(${duration}s / var(--zw-scene-speed, 1));
  animation-timing-function: ease;
  animation-iteration-count: infinite;
}

@keyframes pattern${i} {
  0% {
    opacity: 0;
  }
  40% {
    opacity: 0;
    transform: scale(0.1);
  }
  50% {
    opacity: 1;
  }
  100% {
    transform: scale(${scale});
    opacity: 0;
  }
}`);
}

blocks.push(`.fireworks[data-static="true"] {
  animation: none; opacity: 0.85; transform: scale(1);
}`);

blocks.push(`.sizing {
  width: 100lvmax;
  height: 100lvmax;
}`);

blocks.push(`@media (prefers-reduced-motion: reduce) {
  ${Array.from({ length: COUNT + 1 }, (_, i) => `.pattern${i}`).join(",\n  ")} {
    animation: none;
    opacity: 0.85;
    transform: scale(1);
  }
}`);

const css = `${blocks.join("\n\n")}\n`;
const check = process.argv.includes("--check");
if (check) {
  if (readFileSync(OUT_PATH, "utf8") !== css) { console.error(`Stale generated celebration CSS: ${OUT_PATH}`); process.exitCode = 1; }
  else console.log("Celebration CSS is current");
} else { writeFileSync(OUT_PATH, css, "utf8"); console.log(`wrote ${OUT_PATH}`); }
console.log(`${(Buffer.byteLength(css, "utf8") / 1024).toFixed(1)} KB, ${COUNT + 1} bursts`);
