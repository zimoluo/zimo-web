import { brotliCompressSync, constants, gzipSync } from "node:zlib";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve as resolvePath } from "node:path";
import { compileToCss } from "@/src/features/theme/compile/compile";
import { resolve, schemesOf } from "@/src/features/theme/model/resolve";
import { getTheme, themeOrder } from "@/src/features/theme/registry";

const ROOT = resolvePath(import.meta.dirname, "..");
const OUT_PATH = join(ROOT, "src/styles/themes.generated.css");
const BUDGET_BYTES = 60 * 1024;

const args = new Set(process.argv.slice(2));
const check = args.has("--check");

const blocks: string[] = [
  "/* Generated by tools/build-theme-css.ts. Do not edit; run the tool. */",
];

let schemeCount = 0;

for (const id of themeOrder) {
  const source = getTheme(id);
  for (const scheme of schemesOf(source)) {
    blocks.push(
      compileToCss(
        resolve(source, scheme),
        `[data-theme="${id}"][data-scheme="${scheme}"]`,
      ),
    );
    schemeCount += 1;
  }
}

const css = `${blocks.join("\n\n")}\n`;
const raw = Buffer.byteLength(css, "utf8");
const brotli = brotliCompressSync(Buffer.from(css, "utf8"), {
  params: { [constants.BROTLI_PARAM_QUALITY]: 11 },
}).byteLength;
const gzip = gzipSync(Buffer.from(css, "utf8"), { level: 9 }).byteLength;

const kb = (bytes: number): string => `${(bytes / 1024).toFixed(1)} KB`;

console.log("=== theme CSS ===");
console.log(`themes         : ${themeOrder.length}`);
console.log(`theme x scheme : ${schemeCount}`);
console.log(`raw            : ${kb(raw)}`);
console.log(`gzip           : ${kb(gzip)}`);
console.log(`brotli         : ${kb(brotli)}`);
console.log(`budget (S5)    : ${kb(BUDGET_BYTES)} brotli`);
console.log(
  `S5             : ${brotli < BUDGET_BYTES ? "PASS" : "FAIL"} (${((brotli / BUDGET_BYTES) * 100).toFixed(1)}% of budget)`,
);

if (check) {
  const { readFileSync, existsSync } = await import("node:fs");
  if (!existsSync(OUT_PATH)) {
    console.error(`\n--check: ${OUT_PATH} does not exist. Run the tool without --check.`);
    process.exit(1);
  }
  const existing = readFileSync(OUT_PATH, "utf8");
  if (existing !== css) {
    console.error("\n--check: themes.generated.css is stale. Regenerate it.");
    process.exit(1);
  }
  console.log("\n--check: themes.generated.css is up to date (T4 C6).");
  process.exit(brotli < BUDGET_BYTES ? 0 : 1);
}

mkdirSync(dirname(OUT_PATH), { recursive: true });
writeFileSync(OUT_PATH, css, "utf8");
console.log(`\nwrote ${OUT_PATH}`);

process.exit(brotli < BUDGET_BYTES ? 0 : 1);
