import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE ?? 'playwright');
const base = process.argv[2] ?? 'http://localhost:3483';
const output = process.env.SMOKE_OUTPUT ?? 'work/site-fidelity-smoke';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'], ...(process.env.CHROME_EXECUTABLE ? { executablePath: process.env.CHROME_EXECUTABLE } : {}) });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
await context.addInitScript(() => localStorage.setItem('zw.theme', JSON.stringify({ version: 1, state: { revision: 0, active: { kind: 'builtIn', id: 'whiteout' }, scheme: 'light', schemePreference: 'light', profiles: [], seasonal: false, shuffle: false, byRoute: {} } })));
const page = await context.newPage(), errors = [], results = [];
page.on('pageerror', error => errors.push(error.message));
const visit = async (path, theme) => {
  const response = await page.goto(base + path, { waitUntil: 'domcontentloaded' });
  assert((await response.text()).includes(`data-theme="${theme}"`), `${path} has the wrong server-rendered theme`);
  await page.waitForFunction(id => document.documentElement.dataset.theme === id, theme);
  await page.evaluate(() => document.fonts.ready);
  await page.waitForTimeout(1200);
  assert((await page.locator('body').evaluate(node => getComputedStyle(node).fontFamily)).includes('Inter'));
};
try {
  for (const [path, theme] of [['/', 'whiteout'], ['/projects', 'projects'], ['/album', 'photos'], ['/blog', 'blog'], ['/about', 'about'], ['/design', 'velvet'], ['/notebook', 'cherry'], ['/management', 'unity'], ['/design/theme-maker', 'penumbra']]) {
    await visit(path, theme);
    if (theme === 'whiteout' || theme === 'velvet') await page.locator('[data-frame="captured"]').first().waitFor({ state: 'attached', timeout: 30000 });
    await page.screenshot({ path: `${output}/${theme}-desktop.png` });
    results.push({ path, theme });
  }
  await visit('/projects', 'projects');
  const tiles = page.locator('main a[href^="/projects/"]');
  const positions = await tiles.evaluateAll(nodes => nodes.map(node => node.getBoundingClientRect().toJSON()));
  assert.equal(positions.filter(position => Math.abs(position.y - positions[0].y) < 2).length, 6);
  const moving = await page.locator('[data-scene-id="projects"]').evaluate(node => node.getAnimations({ subtree: true }).some(animation => animation.playState === 'running'));
  assert(moving);
  const opener = page.locator('a[href="/projects/notex"]').first();
  await opener.click();
  const dialog = page.locator('dialog[data-kind="project-entry"]');
  await dialog.getByRole('heading', { name: 'NoTeX', exact: true }).first().waitFor();
  const panel = await dialog.evaluate(node => ({ width: node.clientWidth, color: getComputedStyle(node).color, backdrop: getComputedStyle(node, '::backdrop').backgroundColor }));
  assert(panel.width > 1200);
  assert.notEqual(panel.color, 'rgb(0, 0, 0)');
  assert(panel.backdrop.includes('0.3'));
  const controls = await dialog.getByRole('button', { name: 'Close', exact: true }).boundingBox();
  assert(controls.y < 60);
  await dialog.locator('[data-index="0"] img').evaluate(image => image.decode());
  await page.screenshot({ path: `${output}/project-overlay.png` });
  const expand = dialog.getByRole('button', { name: 'Expand', exact: true });
  await expand.click();
  const lightbox = page.locator('dialog[data-kind="lightbox"]');
  await lightbox.getByRole('link', { name: 'Original', exact: true }).waitFor();
  assert.equal(await dialog.locator('button[aria-label="Close"]').isVisible(), false);
  await lightbox.locator('[data-index="0"] img').evaluate(image => image.decode());
  await lightbox.getByRole('button', { name: 'Next image', exact: true }).click();
  await lightbox.locator('[aria-live="polite"]').filter({ hasText: 'Image 2 of 3' }).waitFor();
  await lightbox.locator('[data-index="1"] img').evaluate(image => image.decode());
  assert.equal(await lightbox.locator('[data-index="1"] img').evaluate(image => getComputedStyle(image).backgroundImage), 'none');
  await page.screenshot({ path: `${output}/project-lightbox.png` });
  await page.setViewportSize({ width: 390, height: 844 });
  assert((await lightbox.boundingBox()).width <= 390);
  await page.screenshot({ path: `${output}/project-lightbox-mobile.png` });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.keyboard.press('Escape');
  await lightbox.waitFor({ state: 'detached' });
  assert.equal(await expand.evaluate(node => node === document.activeElement), true);
  assert.equal(await dialog.getByRole('button', { name: 'Close', exact: true }).isVisible(), true);
  await page.keyboard.press('Escape');
  await dialog.waitFor({ state: 'detached' });
  assert.equal(await opener.evaluate(node => node === document.activeElement), true);
  await visit('/album', 'photos');
  const columns = await page.locator('main a[href^="/album/"]').evaluateAll(nodes => [...new Set(nodes.map(node => Math.round(node.getBoundingClientRect().x)))]);
  assert.equal(columns.length, 4);
  await visit('/blog/a-gardens-tale', 'blog');
  const reading = await page.locator('article[data-reading-surface="server"]').evaluate(node => ({ width: node.clientWidth, body: getComputedStyle(node.querySelector('[class*="document"]')).fontSize }));
  assert.equal(reading.width, 800);
  assert.equal(reading.body, '20px');
  const blur = await page.locator('[data-scope="viewport"]').evaluate(node => getComputedStyle(node).filter);
  assert.equal(blur, 'blur(24px)');
  await page.screenshot({ path: `${output}/blog-reading.png` });
  await visit('/', 'whiteout');
  await page.getByRole('button', { name: 'Open window picker; Shift click minimizes windows' }).click();
  const picker = page.getByRole('dialog', { name: 'Windows', exact: true });
  await picker.getByRole('heading', { name: 'Entries', exact: true }).waitFor();
  await picker.getByRole('button', { name: 'Calculator', exact: true }).click();
  const calculator = page.getByRole('dialog', { name: 'Calculator', exact: true });
  await calculator.evaluate(() => new Promise(resolve => requestAnimationFrame(resolve)));
  await page.waitForFunction(() => getComputedStyle(document.querySelector('[role="dialog"][aria-label="Calculator"]')).opacity === '1');
  const move = calculator.getByRole('button', { name: 'Move Calculator; Alt and arrow keys resize' });
  await move.focus();
  for (let i = 0; i < 70; i++) await page.keyboard.press('Shift+ArrowDown');
  const bar = await move.boundingBox();
  assert(bar.y + bar.height <= 1000);
  await page.screenshot({ path: `${output}/windows.png` });
  await calculator.getByRole('button', { name: 'Close Calculator', exact: true }).click();
  await calculator.waitFor({ state: 'detached' });
  await picker.getByRole('button', { name: 'Close Windows', exact: true }).click();
  await picker.waitFor({ state: 'detached' });
  await page.setViewportSize({ width: 390, height: 844 });
  for (const [path, theme] of [['/', 'whiteout'], ['/album', 'photos'], ['/projects', 'projects'], ['/blog/a-gardens-tale', 'blog'], ['/notebook', 'cherry']]) {
    await visit(path, theme);
    const width = await page.evaluate(() => ({ document: document.documentElement.scrollWidth, viewport: innerWidth }));
    assert(width.document <= width.viewport + 1, `${path} overflows mobile width`);
    if (theme === 'whiteout') await page.locator('[data-frame="captured"]').first().waitFor({ state: 'attached', timeout: 30000 });
    assert.equal(await page.getByRole('dialog', { name: 'Windows', exact: true }).count(), 0);
    await page.screenshot({ path: `${output}/${theme}-mobile.png` });
  }
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await visit('/projects', 'projects');
  const paused = await page.locator('[data-scene-id="projects"]').evaluate(node => ({ visible: node.querySelectorAll('svg,img').length, running: node.getAnimations({ subtree: true }).filter(animation => animation.playState === 'running').length }));
  assert(paused.visible > 0);
  assert.equal(paused.running, 0);
  assert.deepEqual(errors, []);
  await writeFile(`${output}/report.json`, JSON.stringify({ base, results, panel, reading, blur, paused, errors }, null, 2));
  console.log('PASS original route identities, fonts, composition, reading surfaces, responsive layout, focus restoration and reduced-motion artwork');
} catch (error) {
  await page.screenshot({ path: `${output}/failure.png` }).catch(() => {});
  await writeFile(`${output}/report.json`, JSON.stringify({ failure: String(error), results, errors }, null, 2));
  throw error;
} finally { await browser.close(); }
